import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
const root = path.resolve(import.meta.dirname, "..");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const window = { MIST_DATA: { script: {}, scripts: [], series: [], chapters: [], nodes: {}, clues: {}, endings: {}, defaultFlags: {}, defaultStoryState: {} } };
const context = vm.createContext({ window, console, structuredClone });
vm.runInContext(read("assets/stories/dormitory-namefloor/story-data.js"), context);
vm.runInContext(read("assets/stories/dormitory-namefloor/story-chapters-2-7.js"), context);
const base = window.MIST_DORMITORY_NAMEFLOOR_DATA;
const expansion = window.MIST_DORMITORY_NAMEFLOOR_CHAPTERS_2_7;
const nodes = { ...base.nodes, ...expansion.nodes };
const chapter = expansion.chapters.find((item) => item.chapterId === "namefloor_chapter_07");
const chapterNodes = Object.values(nodes).filter((node) => node.chapterId === "namefloor_chapter_07");
const decisions = chapterNodes.filter((node) => node.type === "choice");
const choices = decisions.flatMap((node) => node.choices || []);
assert.equal(nodes.nf06_050?.nextNodeId, "nf07_001", "Chapter 6 must enter Chapter 7.");
assert.equal(chapter?.status, "runtime", "Chapter 7 must be runtime.");
assert.ok(decisions.length >= 8, "Chapter 7 needs eight decision nodes.");
assert.ok(decisions.filter((node) => node.timedChoice).length >= 2, "Chapter 7 needs two timed decisions.");
assert.ok(choices.some((choice) => choice.setFlags?.includes("legal_linfeng_confirmed")), "Legal-record validation must be playable.");
assert.ok(choices.some((choice) => choice.setFlags?.includes("player_linfeng_continuity_evidence")), "New-memory validation must be playable.");
assert.ok(choices.some((choice) => choice.setFlags?.includes("dual_linfeng_subjects_acknowledged")), "Personhood validation must be playable.");
assert.ok(choices.some((choice) => choice.setFlags?.includes("song_mimic_self_aware")), "Mimic personhood choice must be playable.");
assert.equal(nodes.nf07_decision_entry?.nextNodeId, "nf_end_resolve", "Chapter 7 must enter the deterministic ending resolver.");
assert.deepEqual(Object.keys(expansion.endings || {}).sort(), ["E1", "E2", "E3", "E4", "E5", "E6", "E7", "E8"], "Chapter 7 must feed all eight formal ending bodies through one resolver.");
console.log(`Dormitory Chapter 7 check passed. nodes=${chapterNodes.length}; decisions=${decisions.length}`);
